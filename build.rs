//! Embeds every route in assets/routes, and the map data in assets/maps,
//! into the binary.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn json_files(dir: &Path) -> Vec<PathBuf> {
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut files: Vec<PathBuf> = std::fs::read_dir(dir)
        .map(|rd| {
            rd.flatten()
                .map(|e| e.path())
                .filter(|p| p.extension().is_some_and(|e| e == "json"))
                .collect()
        })
        .unwrap_or_default();
    files.sort();
    for f in &files {
        println!("cargo:rerun-if-changed={}", f.display());
    }
    files
}

fn main() {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let mut out = String::from(
        "/// Real routes as JSON, generated by build.rs.\nstatic ROUTE_FILES: &[&str] = &[\n",
    );
    for f in json_files(&root.join("assets/routes")) {
        writeln!(out, "    include_str!({:?}),", f.display().to_string()).unwrap();
    }
    out.push_str("];\n\n/// OpenStreetMap data per route id, generated by build.rs.\nstatic MAP_FILES: &[(&str, &str)] = &[\n");
    for f in json_files(&root.join("assets/maps")) {
        let id = f.file_stem().unwrap().to_string_lossy().to_string();
        writeln!(
            out,
            "    ({id:?}, include_str!({:?})),",
            f.display().to_string()
        )
        .unwrap();
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("routes.rs");
    std::fs::write(dest, out).unwrap();
}
